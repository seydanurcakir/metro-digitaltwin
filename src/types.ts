// Metro Twin — data model types.
// No UI code. Every number is tied to a source (Provenance).

/** Where a number comes from. */
export type ProvenanceKind =
  | 'published' // taken from an official publication (e.g. SL annual report)
  | 'derived' // computed from published values
  | 'assumption' // reasonable assumption, to be replaced with a real value
  | 'synthetic'; // synthetic data generated by the model

export interface Provenance {
  kind: ProvenanceKind;
  /** Source key in sources.ts */
  ref: string;
  note?: string;
}

/** A value together with its source. */
export interface Sourced<T> {
  value: T;
  src: Provenance;
}

/** Metro (T) and commuter rail (J) lines */
export type LineId = 'T13' | 'T14' | 'J40' | 'J41' | 'J42X' | 'J43' | 'J43X' | 'J44';
export type LineMode = 'metro' | 'commuter';

/** Increasing station order = north. T14: towards Mörby centrum; commuter corridor: towards Solna/Ulriksdal */
export type Direction = 'north' | 'south';
export const DIRECTIONS: Direction[] = ['north', 'south'];

export interface Platform {
  /** Platform area usable for waiting (m²), both directions together */
  usableAreaM2: Sourced<number>;
  /** Share of the island platform area serving one direction */
  areaShareByDirection: Sourced<number>;
  lengthM: Sourced<number>;
}

export interface Station {
  id: string;
  name: string;
  /** Position on the line (from 0) */
  order: number;
  isTerminal: boolean;
  servedBy: LineId[];
  /** On a trunk shared with other lines (T14: with T13; corridor: Citybanan) */
  onTrunk: boolean;
  /** Average winter weekday boardings of the station for this mode */
  boardingsPerDay: Sourced<number>;
  /** Share of those boardings that use trains of the modelled line */
  lineShare: Sourced<number>;
  /** Virtual node at the corridor edge: passengers coming from / going beyond the corridor. Excluded from metrics. */
  isBoundary?: boolean;
  /** Dwell time at the platform (doors open) */
  dwellSec: Sourced<number>;
  platform: Platform;
}

export interface Segment {
  from: string;
  to: string;
  /** Running time between the two stations (excluding dwell) */
  runTimeSec: Sourced<number>;
}

export interface Line {
  id: LineId;
  /** In a corridor several lines share the track (e.g. J40, J41, J42X) */
  lineIds?: LineId[];
  mode?: LineMode;
  name: string;
  color: string;
  stations: Station[];
  segments: Segment[];
  /** Turnaround time at the terminals */
  turnaroundSec: Sourced<number>;
  trunk: {
    fromStationId: string;
    toStationId: string;
    /** Maximum trains per hour on the shared trunk (all lines together) */
    maxTrainsPerHour: Sourced<number>;
  };
}

export interface TrainUnitType {
  id: string;
  seats: Sourced<number>;
  standing: Sourced<number>;
  lengthM: Sourced<number>;
}

export interface Fleet {
  unitType: TrainUnitType;
  /** Allowed numbers of units per train (short / long train) */
  allowedUnitsPerTrain: Sourced<number[]>;
  /** Total units available for this line */
  unitsAvailable: Sourced<number>;
}

/** 15-minute time slot */
export interface TimeSlot {
  index: number;
  /** Minutes since start of day (05:00 = 300). After midnight it can be 1440+. */
  startMin: number;
  label: string;
}

export interface DemandProfile {
  slotMinutes: number;
  slots: TimeSlot[];
  /** Share of daily demand in each slot; sums to 1 */
  shares: number[];
  src: Provenance;
}

/** Passengers arriving on the platform at one station, in one direction, during one slot */
export interface DemandCell {
  slotIndex: number;
  stationId: string;
  direction: Direction;
  arrivals: number;
}

/** Demand period: morning peak weighted towards the centre, evening peak away from it */
export type OdPeriod = 'am' | 'pm' | 'base';

/** Distribution of passengers boarding at a station over destination stations */
export interface OdRow {
  period: OdPeriod;
  originId: string;
  direction: Direction;
  /** destinationId -> share; sums to 1 */
  destinationShares: Record<string, number>;
}

export interface Demand {
  profile: DemandProfile;
  cells: DemandCell[];
  od: OdRow[];
  /** Demand period of each slot */
  periodBySlot: OdPeriod[];
  /** Directional bias factors */
  directionalBias: Sourced<{ am: number; pm: number; centerStationId: string }>;
  src: Provenance;
}

/** Service plan decision for one slot */
export interface PlanSlot {
  slotIndex: number;
  /** Time between two trains (minutes) */
  headwayMin: number;
  /** Number of units per train */
  unitsPerTrain: number;
}

export interface ServicePlan {
  id: string;
  name: string;
  kind: 'current' | 'candidate';
  slots: PlanSlot[];
  src: Provenance;
}

/** Trains of the other line (T13) using the shared trunk */
export interface OtherLineService {
  lineId: LineId;
  /** slot index -> trains per hour */
  trainsPerHourBySlot: number[];
  src: Provenance;
}

export interface Constraints {
  minHeadwayMin: Sourced<number>;
  maxHeadwayMin: Sourced<number>;
  /** Train load limit (share of capacity) */
  maxLoadFactor: Sourced<number>;
  /** Safe platform density limit (people/m²) */
  platformDensityLimit: Sourced<number>;
}

/** Metrics the simulation produces for each plan */
export interface Kpis {
  /** Primary KPI: time within which 90% of arriving passengers have boarded and left the platform (s) */
  dispersionP90Sec: number;
  /** Highest train load factor (0–1+) */
  peakLoadFactor: number;
  /** Average platform waiting time (s) */
  avgWaitSec: number;
  /** Highest platform density (people/m²) */
  maxPlatformDensity: number;
  /** Passengers who could not board and wait for the next train */
  leftBehind: number;
}

export interface SourceRef {
  id: string;
  title: string;
  url?: string;
  note?: string;
}

export interface TwinDataset {
  line: Line;
  fleet: Fleet;
  demand: Demand;
  plans: ServicePlan[];
  otherLine: OtherLineService;
  constraints: Constraints;
  sources: SourceRef[];
}
